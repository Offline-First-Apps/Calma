# ASCII ONLY. Windows PowerShell 5.1 reads a script as ANSI unless it has a
# BOM, so a single em dash in a here-string gets written into the repo doubly
# encoded. Check with:
#   python -c "print(sum(1 for b in open('progress/commit-session-11.ps1','rb').read() if b>127))"
#
# Safe to re-run: every step skips when there is nothing staged.

$ErrorActionPreference = 'Stop'
Set-Location (Join-Path $PSScriptRoot '..')

function Commit-Step {
    param(
        [string[]] $Paths,
        [string]   $Message,
        [string]   $Todo
    )

    foreach ($p in $Paths) {
        if (Test-Path $p) { git add -A -- $p }
    }

    if (git diff --cached --quiet) {
        Write-Host "skip  $Message" -ForegroundColor DarkGray
        return
    }

    git commit -q -m $Message
    $sha = (git rev-parse --short HEAD)
    Write-Host "$sha  $Message" -ForegroundColor Green

    if ($Todo) {
        foreach ($plan in @(
            'plans/08-worry-postponement.md',
            'plans/09-journaling.md'
        )) {
            if (-not (Test-Path $plan)) { continue }
            $text = Get-Content $plan -Raw
            if ($text -match [regex]::Escape("pending-$Todo")) {
                $text = $text -replace [regex]::Escape("pending-$Todo"), $sha
                Set-Content $plan $text -NoNewline
                Write-Host "      $plan  $Todo -> $sha" -ForegroundColor DarkGray
            }
        }
    }
}

