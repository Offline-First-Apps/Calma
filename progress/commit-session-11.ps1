Commit-Step -Todo 'T06' -Paths @('apps/native/src/features/journal/useAutosave.ts') -Message @'
feat(journal): add continuous draft autosave

A half-written journal entry is the most emotionally costly thing this app
holds. Losing one is worse than a crash, because a crash does not take
anything with it.

So saving is continuous and debounced at 800ms, not on blur. Blur-only saving
loses everything typed into the field that was focused when the phone was
killed -- which is, by definition, the field they were in the middle of.

Three overlapping triggers: the debounce, AppState leaving active (the last
code that runs before iOS may suspend and then kill), and unmount. The dirty
buffer is cleared before the await, so keystrokes landing during a write are
recorded as newly dirty rather than wiped by the completion of a save that did
not include them.
'@

